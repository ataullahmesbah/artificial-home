// Builds ONE ready-to-run SQL file that installs this website into its own schema,
// so several websites can share a single Supabase project (each with separate data,
// admins and storage bucket).
//
//   npm run schema:sql -- site01
//
// Output: supabase/schemas/site01.sql  → paste it into Supabase → SQL Editor → Run.
// Normal client installs do NOT need this (they use the "public" schema and the
// files in supabase/migrations as described in the README).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const schema = (process.argv[2] ?? "").trim().toLowerCase();
if (!/^[a-z][a-z0-9_]{0,30}$/.test(schema) || schema === "public") {
  console.error('Usage: npm run schema:sql -- <schema>   e.g. site01 (letters, numbers, "_"; not "public")');
  process.exit(1);
}
const bucket = `${schema.replace(/_/g, "-")}-media`;
const dir = new URL("../supabase/", import.meta.url);
const migrations = readdirSync(new URL("migrations/", dir))
  .filter((f) => f.endsWith(".sql"))
  .sort();

const parts = migrations.map((f) => `-- >>> ${f}\n` + readFileSync(new URL(`migrations/${f}`, dir), "utf8"));
parts.push("-- >>> seed.sql (demo content)\n" + readFileSync(new URL("seed.sql", dir), "utf8"));

const body = parts
  .join("\n\n")
  .replace(/\bpublic\./g, `${schema}.`)
  .replace(/set search_path = public\b/g, `set search_path = ${schema}`)
  .replace(/'portfolio-media'/g, `'${bucket}'`)
  // Storage policies live on one shared table, so their names must be unique per website.
  .replace(/"([^"]+)" on storage\.objects/g, `"$1 [${schema}]" on storage.objects`)
  // Make every policy and trigger re-runnable (the original migrations create some of them only once).
  .replace(/^create policy ("[^"]+") on ([\w.]+)/gm, "drop policy if exists $1 on $2;\ncreate policy $1 on $2")
  .replace(/execute format\('create policy ("[^"]+") on (\S+) /g, "execute format('drop policy if exists $1 on $2', t);\n    execute format('create policy $1 on $2 ")
  .replace(/'create trigger (\w+) before update on (\S+) /g, "'drop trigger if exists $1 on $2; create trigger $1 before update on $2 ");

const header = `-- =====================================================================
-- Website installed into schema "${schema}" (generated by scripts/build-schema-sql.mjs).
-- Storage bucket: "${bucket}".
-- WARNING: run this file ONCE. Running it again replaces all website content with the demo content
-- (messages and admins are kept).
--
-- AFTER running this file:
--   1. Project Settings → Data API → "Exposed schemas": add ${schema}  (then Save)
--   2. Website .env: NEXT_PUBLIC_SUPABASE_SCHEMA=${schema}
--   3. Make your owner an admin of this website (bottom of this file).
-- =====================================================================

create schema if not exists ${schema};
grant usage on schema ${schema} to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant all on tables to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant execute on functions to anon, authenticated, service_role;
-- Row Level Security (enabled on every table below) still decides who can read or write.

`;

const footer = `

-- Tables that already existed before a re-run keep their grants; make sure they are set.
grant select, insert, update, delete on all tables in schema ${schema} to anon, authenticated, service_role;
revoke update on ${schema}.admins from anon, authenticated;
grant update (display_name, avatar_url) on ${schema}.admins to authenticated;

-- Make the dashboard owner for THIS website (create the user first in Authentication → Users):
-- insert into ${schema}.admins (user_id, display_name)
-- select id, 'Owner Name' from auth.users where email = 'owner@example.com'
-- on conflict (user_id) do update set active = true;
`;

mkdirSync(new URL("schemas/", dir), { recursive: true });
writeFileSync(new URL(`schemas/${schema}.sql`, dir), header + body + footer);
console.log(`supabase/schemas/${schema}.sql written (bucket "${bucket}")`);
